function buildStages(status, statusDate) {
  const ALL = [
    "정비구역지정","추진위원회승인","조합설립인가","건축심의",
    "사업시행인가","관리처분인가","이주철거","착공","일반분양","준공"
  ];
  const idx = ALL.indexOf(status);
  return ALL.map((name, i) => ({
    name,
    isCompleted: i < idx,
    isCurrent: i === idx,
    date: i <= idx ? statusDate : undefined,
  }));
}

